function genHex32() {
  return crypto.randomBytes(32).toString('hex'); // 64 hex chars
}

function parseEnv(text) {
  const lines = text.split(/\r?\n/);
  const map = new Map();
  for (const line of lines) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (!m) continue;
    const key = m[1];
    let val = m[2] ?? '';
    // Strip simple surrounding quotes (common in env files).
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    map.set(key, val);
  }
  return { lines, map };
}

function isWeakOrDefaultSecret(v) {
  if (!v) return true;
  const s = String(v).toLowerCase();
  if (s.includes('change-me') || s.includes('not-secure') || s.includes('csrf-dev-secret')) return true;
  // Accept either 32+ chars (arbitrary) or 32-byte hex (64 chars).
  return v.length < 32;
}

function setKey(lines, key, value) {
  const re = new RegExp(`^\\s*${key}\\s*=`);
  for (let i = 0; i < lines.length; i++) {
    if (re.test(lines[i])) {
      lines[i] = `${key}=${value}`;
      return;
    }
  }
  lines.push(`${key}=${value}`);
}

